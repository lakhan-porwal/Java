package in.co.rays;

public class Switch_case {
	
	public static void main(String[] args) {
		
		int number = 10;
		
		switch (number) {
		case 2: 
			System.out.println("two");
		case 5: 
			System.out.println("five");
		case 10:
			System.out.println("ten");
		default:
			System.out.println();
		}
		
	}
}
